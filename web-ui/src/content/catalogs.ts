export type Catalog = (typeof catalogs)[number];
export type CatalogId = Catalog['id'];
export type BookingType = Catalog['bookingType'] | 'general';

export function catalogById(id: CatalogId): Catalog {
  const catalog = catalogs.find((item) => item.id === id);
  if (!catalog) throw new Error(`Unknown catalog ${id}`);
  return catalog;
}

export const homeRails = catalogs.filter(
  (catalog): catalog is Extract<Catalog, { home: 'rail' }> => catalog.home === 'rail',
);

export const homeLinks = catalogs.filter((catalog) => catalog.home === 'link');
